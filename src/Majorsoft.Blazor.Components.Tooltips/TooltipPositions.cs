namespace Majorsoft.Blazor.Components.Tooltips
{
	/// <summary>
	/// Defines where the Tooltip popup is rendered relative to its trigger element.
	/// </summary>
	public enum TooltipPositions
	{
		/// <summary>
		/// Tooltip is shown above the trigger element.
		/// </summary>
		Top,
		/// <summary>
		/// Tooltip is shown to the right of the trigger element.
		/// </summary>
		Right,
		/// <summary>
		/// Tooltip is shown below the trigger element.
		/// </summary>
		Bottom,
		/// <summary>
		/// Tooltip is shown to the left of the trigger element.
		/// </summary>
		Left
	}
}
